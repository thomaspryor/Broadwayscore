// Server component — loads data at build time, passes serialized props to client
import fs from 'fs';
import crypto from 'crypto';
import { Suspense } from 'react';
import type { Metadata } from 'next';
import { getBroadwayShows, getNotableOffBroadwayShows, getDataStats, getSiteStats, getUpcomingShows, getMarketStats } from '@/lib/data-core';
import { getAwardWinnerSets } from '@/lib/data-awards';
import type { ComputedShow } from '@/lib/data-types';
import { createShowSerializer } from '@/lib/serialize-show';
import { hasEnoughReviews } from '@/config/score-buckets';
import { BASE_URL, generateHomepageFAQSchema } from '@/lib/seo';
import { getOptimizedImageUrl } from '@/lib/images';
import { getServerImageSrcSet } from '@/lib/show-image-srcset.server';
import HomePageClient from '@/components/HomePageClient';
import type { HomepageShow } from '@/components/HomePageClient';
import FeaturedRowServer from '@/components/FeaturedRowServer';
import FeaturedSpotSlim from '@/components/FeaturedSpotSlim';
import { getTonyTrackRecord, getTonySeasonWindow, isTonyPromoActive, isBtcPromoActive, currentCeremonyShortDate } from '@/lib/data-tony-predictions';
import { isDraftOpen, draftDeadlineDate, PRIZE_VALUE } from '@/config/fantasy';
import { isFantasyListed } from '@/config/fantasy-listing';
import { formatShowDate } from '@/lib/date-utils';

const homeOgImageUrl = `${BASE_URL}/og/home.png`;
const currentYear = new Date().getFullYear();

export const metadata: Metadata = {
  title: `Broadway Scorecard: Best Broadway Shows ${currentYear} | Aggregated Critic Reviews & Ratings`,
  description: 'Find the best Broadway shows with scores aggregated from every major critic. Compare ratings from The New York Times, Vulture, Variety, and 400+ outlets. Updated daily.',
  alternates: {
    canonical: BASE_URL,
  },
  openGraph: {
    type: 'website',
    siteName: 'Broadway Scorecard',
    title: `Broadway Scorecard: Best Broadway Shows ${currentYear}`,
    description: 'Find the best Broadway shows with scores aggregated from every major critic. Compare ratings from The New York Times, Vulture, Variety, and 400+ outlets.',
    url: BASE_URL,
    images: [{ url: homeOgImageUrl, width: 1200, height: 630, alt: 'Broadway Scorecard: Aggregated Critic Scores for Every Broadway Show' }],
  },
  twitter: {
    card: 'summary_large_image',
    title: `Broadway Scorecard: Best Broadway Shows ${currentYear}`,
    description: 'Aggregated critic scores for every Broadway show. Compare ratings from 400+ outlets.',
    images: [{ url: homeOgImageUrl, width: 1200, height: 630, alt: 'Broadway Scorecard: Aggregated Critic Scores for Every Broadway Show' }],
  },
};

export default function HomePage() {
  // Memoized per-render: the same show appears in the full grid AND several
  // featured shelves (Tony Winners, Date Night, Closing Soon, ...). Sharing one
  // serialized object reference per show lets the RSC flight serializer dedupe
  // repeat occurrences instead of re-inlining criticScore/images/etc each time.
  const serialize = createShowSerializer();
  function serializeShow(show: ComputedShow): HomepageShow {
    return serialize(show) as HomepageShow;
  }
  const allShows = getBroadwayShows();
  const stats = getDataStats();
  const siteStats = getSiteStats();
  const upcomingShows = getUpcomingShows();
  // Live headline accuracy — same number rendered on the season-specific
  // predictions page. Lives here so the homepage promo never drifts.
  const tonyTrackRecord = getTonyTrackRecord(allShows);
  // Tony promo auto-hides 2 days after the ceremony.
  const tonyPromoActive = isTonyPromoActive();
  // Same season isTonyPromoActive() gates on, so the promo never points at
  // last year's predictions once the next ceremony date is recorded.
  const tonyPromoSeason = getTonySeasonWindow();
  // Fantasy League draft window (BRO-5483): the game is otherwise linked only
  // from the footer. Takes the slot ahead of the Tony promo for those weeks.
  // The page is static, so this flips at the next deploy (the deploy gate's
  // 6h backstop plus build time, so up to ~6.5h late).
  const fantasyPromoActive = isFantasyListed() && isDraftOpen();
  const fantasyDeadline = formatShowDate(draftDeadlineDate(), { month: 'short', day: 'numeric' });
  const btcPromoActive = isBtcPromoActive();

  // Only pass active (non-closed) shows as props — archive is lazy-loaded from
  // public/data/homepage-archive.json (generated by scripts/generate-homepage-archive.js)
  const broadwayActive = allShows.filter(s => s.status !== 'closed');
  // Mix a small, capped set of NOTABLE off-Broadway shows into the main grid so
  // it doesn't go stale when Broadway openings are sparse. Each renders with an
  // "Off-Bway" category badge (showCategoryBadge in ShowCardList). The OB market
  // pill count + /off-broadway page are unaffected — this only seeds the grid.
  // Notability rule: src/lib/homepage-notability.ts.
  const broadwayIds = new Set(broadwayActive.map(s => s.id));
  const notableOffBroadway = getNotableOffBroadwayShows()
    .filter(s => s.status !== 'closed' && !broadwayIds.has(s.id));
  const activeShows = [...broadwayActive, ...notableOffBroadway];
  // One hash covers both lazy-loaded archives (Broadway closed shows + closed
  // West End search entries), so either regenerating busts the client cache.
  const archiveHash = crypto.createHash('md5')
    .update(fs.readFileSync(process.cwd() + '/public/data/homepage-archive.json'))
    .update(fs.readFileSync(process.cwd() + '/public/data/west-end-archive.json'))
    .digest('hex').slice(0, 8);

  // Precompute "Best Recent Shows" server-side for both preload links and SSR featured row
  const twelveMonthsAgo = new Date();
  twelveMonthsAgo.setMonth(twelveMonthsAgo.getMonth() - 12);
  const shelfScoreFilter = (s: typeof allShows[number]) =>
    s.criticScore?.score && hasEnoughReviews(
      s.criticScore.reviewCount ?? 0, s.category,
      (s.criticScore.tier1Count ?? 0) + (s.criticScore.tier2Count ?? 0)
    );

  const bestRecentShows = allShows
    .filter(s => (s.type === 'musical' || s.type === 'play') && s.status === 'open' && new Date(s.openingDate) >= twelveMonthsAgo && shelfScoreFilter(s))
    .sort((a, b) => (b.criticScore?.score || 0) - (a.criticScore?.score || 0))
    .slice(0, 10)
    .map(serializeShow);

  // Preload the LCP poster only; the other first-row posters load eagerly
  // from the markup without competing with it.
  const featuredPosterUrls = bestRecentShows
    .slice(0, 1)
    .map(s => {
      const img = s.images?.poster || s.images?.thumbnail;
      if (!img) return null;
      const href = getOptimizedImageUrl(img, 'card');
      // Match the <img> srcset/sizes in FeaturedRowServer so the browser preloads the file it will use.
      return { href, srcSet: getServerImageSrcSet(href) };
    })
    .filter((u): u is { href: string; srcSet: string } => !!u);

  return (
    <>
      {featuredPosterUrls.map(({ href, srcSet }, i) => (
        <link key={`preload-${i}`} rel="preload" as="image" href={href} fetchPriority="high"
          {...(srcSet ? { imageSrcSet: srcSet, imageSizes: '(min-width: 640px) 128px, 112px' } : {})} />
      ))}
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(generateHomepageFAQSchema({ totalShows: siteStats.scoredShows, totalReviews: siteStats.totalReviews })) }}
      />
      {/* Server-rendered hero + featured row — LCP image appears in initial HTML, no JS needed */}
      <div className="max-w-3xl mx-auto px-4 sm:px-6 pt-5 sm:pt-12">
        <div className="mb-4 sm:mb-8">
          <h1 className="sr-only sm:not-sr-only sm:text-5xl lg:text-6xl font-extrabold text-white mb-4 sm:mb-5 tracking-tight">
            Broadway<span className="text-gradient">Scorecard</span><span className="text-xs text-gray-400 font-normal align-super ml-0.5">™</span>
          </h1>
          <p className="text-gray-400 text-lg sm:text-xl">
            Every show. Every review. One score.
          </p>
          <p className="text-fg-muted text-sm sm:text-base mt-1">
            {siteStats.scoredShows.toLocaleString('en-US')} scored shows. {siteStats.totalReviews.toLocaleString('en-US')} critic reviews. <span className="whitespace-nowrap">And counting.</span>
          </p>
        </div>
        {/* Above-fold slim promo. Order: the Fantasy League while its draft is
            open, else Tony predictions. Swap Tony to BTC by changing the
            props (BTC config kept below as a comment).
            Beat the Critics swap:
              <FeaturedSpotSlim
                eyebrow="Now playing"
                title="Think you know Broadway better than the critics?"
                ctaLabel="Make your picks"
                href="/beat-the-critics"
                accent="btc"
                stat={{ icon: '★', label: 'Beat the Critics' }}
              /> */}
        {fantasyPromoActive ? (
          <FeaturedSpotSlim
            eyebrow="Broadway Fantasy League"
            title={`Draft open until ${fantasyDeadline}.`}
            ctaLabel="Draft your team"
            href="/fantasy"
            accent="gold"
            stat={PRIZE_VALUE ? { value: PRIZE_VALUE, label: 'Prize' } : { label: 'Free to play' }}
            trackingId="homepage_above_fold_fantasy_draft"
          />
        ) : tonyPromoActive && (
          <FeaturedSpotSlim
            eyebrow={`Tony Awards ${tonyPromoSeason.ceremonyYear}`}
            title="Who will win Best Musical?"
            ctaLabel="See the predictions"
            href={`/tony-awards/predictions/${tonyPromoSeason.label}`}
            accent="gold"
            stat={{ value: `${tonyTrackRecord.pct}%`, label: 'Track record' }}
            trackingId="homepage_above_fold_tony_predictions"
          />
        )}
        <FeaturedRowServer shows={bestRecentShows} title="Best Recent Shows" viewAllHref="/browse/best-recent-shows" />
      </div>
      <Suspense>
        <HomePageClient
          renderedAt={Date.now()}
          shows={activeShows.map(serializeShow)}
          archiveHash={archiveHash}
          upcomingShows={upcomingShows.map(serializeShow)}
          totalShows={siteStats.scoredShows}
          totalReviews={siteStats.totalReviews}
          totalCritics={stats.totalCritics}
          totalOutlets={stats.totalOutlets}
          skipHero
          skipFirstMusicals
          marketOpenCounts={{
            broadway: getMarketStats().nyc.openShows,
            // Broadway+ pill = Broadway plus the open curated OB picks in the grid
            // (previews picks are excluded from the grid client-side, so count open only)
            broadwayPlus:
              getMarketStats().nyc.openShows +
              notableOffBroadway.filter(s => s.status === 'open').length,
            offBroadway: getMarketStats().offBroadway?.openShows ?? 0,
          }}
          awardWinnerSets={getAwardWinnerSets()}
          tonyTrackRecord={tonyTrackRecord}
          tonyPromoActive={tonyPromoActive}
          tonyPromoSeason={{ ceremonyYear: tonyPromoSeason.ceremonyYear, label: tonyPromoSeason.label, ceremonyShort: currentCeremonyShortDate() }}
          btcPromoActive={btcPromoActive}
        />
      </Suspense>
    </>
  );
}
