#!/usr/bin/env node
/**
 * Full year-round weekly snapshot of audience-buzz.json.
 *
 * Unlike snapshot-audience-grades.js (Tony-season only, ~161 nominee/eligible
 * shows, Apr-Jun), this captures the ENTIRE audience-buzz corpus — every show,
 * every source — every week, all year. It exists so we can do longitudinal
 * analysis of how each source's audience scores move over time (e.g. Theatr's
 * recovery curve after the Jun 2026 token outage, or how Show Score vs Mezzanine
 * diverge on a show across its run). The live audience-buzz.json is overwrite-
 * only; without this, history is only reconstructable by walking private-repo
 * git commits.
 *
 * Per source we keep every NUMERIC signal field (score, reviewCount, starRating,
 * sentiment, positiveRate, numLikes, numWatched, totalPosts, ...). Non-numeric
 * fields (url, lastUpdated, prodIds, ratingDistribution, suppressed flags) are
 * dropped — they're identifiers/metadata, not longitudinal signals, and keep
 * the file small. Sources are discovered dynamically, so a future source is
 * captured automatically with no code change.
 *
 * Usage:
 *   node scripts/snapshot-audience-full.js                  # snapshot for today (UTC)
 *   node scripts/snapshot-audience-full.js --date=2026-06-21
 *   node scripts/snapshot-audience-full.js --input=/path/to/audience-buzz.json
 *   node scripts/snapshot-audience-full.js --out=/tmp/snap.json   # override output path
 *
 * Output (default): data/audience-history/{YYYY-MM-DD}.json
 * Idempotent: a second run on the same date overwrites that date's file.
 */

const fs = require('fs');
const path = require('path');

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

/**
 * Pure transform: parsed audience-buzz object -> snapshot object. No I/O, no
 * wall-clock (deterministic for tests). `snapshotAt` is added by main() at
 * write time. Per source, keeps only finite numeric fields; a source with no
 * numeric signal is omitted from that show.
 */
function buildSnapshot(buzzObj, date) {
  const shows = (buzzObj && buzzObj.shows) || {};
  const snapshotShows = {};
  const sourceCoverage = {};
  for (const showId of Object.keys(shows)) {
    const sh = shows[showId] || {};
    const entry = {
      title: sh.title ?? null,
      combinedScore: sh.combinedScore ?? null,
      designation: sh.designation ?? null,
      sources: {},
    };
    for (const [srcKey, srcVal] of Object.entries(sh.sources || {})) {
      if (!srcVal || typeof srcVal !== 'object') continue;
      const numericFields = {};
      for (const [field, val] of Object.entries(srcVal)) {
        if (typeof val === 'number' && Number.isFinite(val)) numericFields[field] = val;
      }
      if (Object.keys(numericFields).length > 0) {
        entry.sources[srcKey] = numericFields;
        sourceCoverage[srcKey] = (sourceCoverage[srcKey] || 0) + 1;
      }
    }
    snapshotShows[showId] = entry;
  }
  return {
    _meta: {
      snapshotDate: date,
      sourceLastUpdated: (buzzObj && buzzObj._meta && buzzObj._meta.lastUpdated) || null,
      totalShows: Object.keys(shows).length,
      sourceCoverage,
      // Authoritative list of sources actually present in the data. NOT
      // buzz._meta.sources — that list is hand-maintained and stale (it omits
      // seatplan/lbo/ltd as of 2026-06), which would understate coverage.
      sources: Object.keys(sourceCoverage),
      designationThresholds: (buzzObj && buzzObj._meta && buzzObj._meta.designationThresholds) || null,
      note: 'Full weekly snapshot of audience-buzz.json (all shows, all sources, numeric signal fields). For longitudinal analysis of audience scores over time. Generated by scripts/snapshot-audience-full.js.',
    },
    shows: snapshotShows,
  };
}

function main() {
  const args = process.argv.slice(2);
  const argMap = Object.fromEntries(
    args.filter(a => a.startsWith('--')).map(a => {
      const [k, v] = a.replace(/^--/, '').split('=');
      return [k, v ?? true];
    })
  );

  const ROOT = path.resolve(__dirname, '..');
  const snapshotDate = argMap.date || new Date().toISOString().slice(0, 10);
  if (!DATE_RE.test(snapshotDate)) {
    console.error(`Invalid --date "${snapshotDate}" — expected YYYY-MM-DD`);
    process.exit(1);
  }

  const buzzPath = argMap.input || path.join(ROOT, 'data/audience-buzz.json');
  if (!fs.existsSync(buzzPath)) {
    console.error(`audience-buzz.json not found at ${buzzPath}`);
    process.exit(1);
  }

  const buzz = JSON.parse(fs.readFileSync(buzzPath, 'utf8'));
  if (!buzz.shows || Object.keys(buzz.shows).length === 0) {
    console.error('audience-buzz.json has no shows — refusing to write an empty snapshot.');
    process.exit(1);
  }

  const snapshot = buildSnapshot(buzz, snapshotDate);
  snapshot._meta.snapshotAt = new Date().toISOString();

  const outPath = argMap.out || path.join(ROOT, 'data/audience-history', `${snapshotDate}.json`);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(snapshot, null, 2) + '\n');

  console.log(`Wrote ${outPath}`);
  console.log(`  Total shows:         ${snapshot._meta.totalShows}`);
  console.log(`  Source last updated: ${snapshot._meta.sourceLastUpdated}`);
  console.log('  Per-source coverage:');
  for (const [src, count] of Object.entries(snapshot._meta.sourceCoverage).sort((a, b) => b[1] - a[1])) {
    console.log(`    ${src.padEnd(14)} ${count}`);
  }
}

if (require.main === module) {
  main();
}

module.exports = { buildSnapshot };
