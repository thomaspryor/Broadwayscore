// check-prod-deploy.js --json output -> { '<name>BlobSha': sha } (legacy
// reviews/shows top-level fields folded in so older output still parses).
function baselineBlobShas(j) {
  return {
    ...(j.reviewsBlobSha ? { reviewsBlobSha: j.reviewsBlobSha } : {}),
    ...(j.showsBlobSha ? { showsBlobSha: j.showsBlobSha } : {}),
    ...(j.blobShas && typeof j.blobShas === 'object' ? j.blobShas : {}),
  };
}

function getBaseline() {
  if (process.env.GATE_BASELINE_JSON) {
    try {
      const j = JSON.parse(process.env.GATE_BASELINE_JSON);
      return {
        sha: j.deployedSha || null,
        ageSec: j.ageSec != null ? j.ageSec : null,
        reviewsBlobSha: j.reviewsBlobSha || null,
        showsBlobSha: j.showsBlobSha || null,
        blobShas: baselineBlobShas(j),
      };
    } catch {
      return { sha: null, ageSec: null, reviewsBlobSha: null, showsBlobSha: null, blobShas: {} };
    }
  }
  try {
    const out = execFileSync(
      'node',
      [path.join(__dirname, '..', 'check-prod-deploy.js'), '--json'],
      { encoding: 'utf8', timeout: 30000 }
    );
    const j = JSON.parse(out);
    return {
      sha: j.deployedSha || null,
      ageSec: j.ageSec != null ? j.ageSec : null,
      reviewsBlobSha: j.reviewsBlobSha || null,
      showsBlobSha: j.showsBlobSha || null,
      blobShas: baselineBlobShas(j),
    };
  } catch (e) {
    console.log(`::warning::[content-gate] baseline lookup failed (${e.message.split('\n')[0]}) — failing open`);
    return { sha: null, ageSec: null, reviewsBlobSha: null, showsBlobSha: null, blobShas: {} };
  }
}

// The private core-data repo's blob SHAs for reviews.json + shows.json,
// straight from GitHub's Contents API — no clone needed. GitHub returns
// `sha` (the git blob object hash) for a file of any size even though
// `content` is omitted above the 1MB inline-content cutoff (reviews.json is
// ~17MB); verified live that this exactly equals `git hash-object` on the
// same bytes, which is what the Deploy step stamps onto the Vercel
// deployment (see header comment). Both files are tracked — not reviews.json
// alone — so a shows.json-only change (e.g. a status flip) isn't a second
// blind spot (Codex adversarial review, BRO-3149).
const DATA_REPO = 'thomaspryor/broadway-scorecard-data';
// One Contents API directory listing returns the blob `sha` of every root
// entry (large files included, `content` omitted), so tracking N files costs
// ONE request against the shared REVIEW_TEXTS_TOKEN quota instead of N. The
// listing is capped at 1000 entries and silently truncates past that; a
// truncated listing would read as "file absent", so treat it as a failed lookup.
const LISTING_CAP = 1000;

async function fetchBlobShas(files, token) {
  const res = await fetch(`https://api.github.com/repos/${DATA_REPO}/contents/?ref=main`, {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
    signal: AbortSignal.timeout(15000),
  });
  if (!res.ok) throw new Error(`GitHub API ${res.status} for ${DATA_REPO} root listing`);
  const list = await res.json();
  if (!Array.isArray(list)) throw new Error('root listing was not an array');
  if (list.length >= LISTING_CAP) throw new Error(`root listing hit the ${LISTING_CAP}-entry cap (truncated)`);
  const byName = new Map(list.map((e) => [e.name, e.sha || null]));
  return Object.fromEntries(files.map((f) => [f, byName.get(f) || null]));
}

// Test seam shape: { "<file>": sha } or the legacy { reviewsSha, showsSha }.
function normalizeSeamShas(j) {
  const out = {};
  for (const f of DATA_TRACKED_FILES) out[f] = j[f] || null;
  if (j.reviewsSha) out['reviews.json'] = j.reviewsSha;
  if (j.showsSha) out['shows.json'] = j.showsSha;
  return out;
}

// -> { '<file>': sha|null } for every tracked file, or null when the lookup
// itself failed / is unavailable (unknown, not "absent").
async function getDataBlobShas() {
  if (process.env.GATE_DATA_SHA_JSON) {
    try {
      return normalizeSeamShas(JSON.parse(process.env.GATE_DATA_SHA_JSON));
    } catch {
      return null;
    }
  }
  const token = process.env.REVIEW_TEXTS_TOKEN;
  if (!token) return null;
  try {
    return await fetchBlobShas(DATA_TRACKED_FILES, token);
  } catch (e) {
    console.log(`::warning::[content-gate] data blob sha lookup failed (${e.message}) — failing open`);
    return null;
  }
}

/**
 * Pure: compare current core-data blob SHAs against the ones stamped on the
 * live deployment. Per tracked file:
 *   both known           -> equal = clean, different = dirty
 *   absent on both sides -> ignored (a file the repo does not have yet)
 *   known on ONE side    -> error (e.g. first deploy after a file joined the
 *                           tracked set: the baseline was stamped without it)
 * Any dirty file wins; then any error; then clean if at least one pair was
 * compared; null when nothing is known at all.
 *
 * @param {Object<string,string|null>|null} nowShas   keyed by file name; null = lookup failed
 * @param {Object<string,string>} baselineBlobShas    keyed by `<name>BlobSha` meta key
 */
function compareDataShas(nowShas, baselineBlobShas, files = DATA_TRACKED_FILES) {
  const base = baselineBlobShas || {};
  if (!nowShas) return Object.keys(base).length ? 'error' : null;
  let dirty = false;
  let error = false;
  let compared = 0;
  for (const f of files) {
    const now = nowShas[f] || null;
    const was = base[blobShaMetaKey(f)] || null;
    if (now && was) {
      compared++;
      if (now !== was) dirty = true;
    } else if (now || was) {
      error = true;
    }
  }
  if (dirty) return 'dirty';
  if (error) return 'error';
  return compared > 0 ? 'clean' : null;
}

function git(args, opts = {}) {
  return execFileSync('git', args, { encoding: 'utf8', ...opts });
}

function runDiff(baselineSha, headSha) {
  try {
    git(['fetch', '--depth=1', 'origin', baselineSha], { stdio: 'ignore', timeout: 60000 });
  } catch {
    return { result: 'error', files: [] };
  }
  let code = 0;
  try {
    git(['diff', '--quiet', '--no-renames', baselineSha, headSha, '--', ...SITE_PATHS], { stdio: 'ignore' });
  } catch (e) {
    code = typeof e.status === 'number' ? e.status : 128;
  }
  const result = classifyDiffExit(code);
  let files = [];
  if (result === 'dirty') {
    try {
      files = git(['diff', '--name-only', '--no-renames', baselineSha, headSha, '--', ...SITE_PATHS])
        .trim().split('\n').filter(Boolean).slice(0, 20);
    } catch { /* listing is best-effort */ }
  }
  return { result, files };
}

function writeOutput(proceed, reason) {
  const lines = `proceed=${proceed}\nreason=${reason}\n`;
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, lines);
  else process.stdout.write(lines);
}

async function main() {
  const eventName = process.env.GATE_EVENT_NAME || 'schedule';
  const gateDisabled = process.env.GATE_DISABLED === 'true';
  const headSha = process.env.GATE_HEAD_SHA || git(['rev-parse', 'HEAD']).trim();

  const baseline = gateDisabled
    ? { sha: null, ageSec: null, reviewsBlobSha: null, showsBlobSha: null }
    : getBaseline();

  // Only run the (fetch + diff) when the decision can actually depend on it.
  let diff = { result: null, files: [] };
  if (
    !gateDisabled &&
    eventName === 'schedule' &&
    baseline.sha && baseline.sha !== headSha &&
    baseline.ageSec != null && baseline.ageSec <= STALENESS_BACKSTOP_SEC
  ) {
    diff = runDiff(baseline.sha, headSha);
  }

  // Core-data blob-SHA lookup is two cheap API calls (no clone), so unlike
  // the site diff above it's not worth narrowing to the schedule-only window —
  // the non-schedule 'already-live' dedup branch needs it too (see decide()).
  // 'dirty' if EITHER tracked file's blob SHA differs from the live baseline.
  let dataDiffResult = null;
  if (!gateDisabled) {
    dataDiffResult = compareDataShas(await getDataBlobShas(), baseline.blobShas);
  }

  const { proceed, reason } = decide({
    eventName,
    gateDisabled,
    baselineSha: baseline.sha,
    deployAgeSec: baseline.ageSec,
    headSha,
    diffResult: diff.result,
    dataDiffResult,
  });

  const short = (s) => (s ? s.slice(0, 10) : 'unknown');
  const verb = proceed ? 'DEPLOY' : 'SKIP';
  console.log(
    `::notice::[content-gate] ${verb} — reason=${reason} baseline=${short(baseline.sha)} head=${short(headSha)} deployAge=${baseline.ageSec != null ? Math.round(baseline.ageSec / 60) + 'm' : 'unknown'} event=${eventName} dataDiff=${dataDiffResult || 'unknown'}`
  );
  if (diff.files.length) console.log(`::notice::[content-gate] changed site files (first ${diff.files.length}): ${diff.files.join(', ')}`);

  writeOutput(proceed, reason);
}

module.exports = { decide, classifyDiffExit, compareDataShas, SITE_PATHS, SITE_DATA_FILES, STALENESS_BACKSTOP_SEC, DATA_TRACKED_FILES };

// `--meta-args`: print `<name>BlobSha=<git blob sha>` for each tracked file
// present in data/, one per line, for vercel-deploy.yml to stamp onto the
// deployment. Names come from core-data-blob-meta.js, same as the read-back.
// A missing file is skipped (a stamped-nothing key reads as "absent").
function printMetaArgs() {
  for (const f of DATA_TRACKED_FILES) {
    const p = path.join('data', f);
    if (!fs.existsSync(p)) continue;
    process.stdout.write(`${blobShaMetaKey(f)}=${git(['hash-object', p]).trim()}\n`);
  }
}

if (require.main === module && process.argv[2] === '--meta-args') {
  printMetaArgs();
} else if (require.main === module) {
  main().catch((e) => {
    console.error(`::error::[content-gate] gate crashed: ${e.stack || e.message}`);
    process.exit(1);
  });
}
