/** Pure: does this trigger skip the reveal check (ship now whatever the range holds)? */
function isAlwaysShip({ eventName, source }) {
  return eventName === 'workflow_dispatch' && ALWAYS_SHIP_SOURCES.includes(String(source || ''));
}

/** Pure: is this trigger an explicit ship-now request? */
function isUrgent({ eventName, source, triggerWorkflow }) {
  if (eventName === 'workflow_dispatch') return URGENT_SOURCES.includes(String(source || ''));
  if (eventName === 'workflow_run') return triggerWorkflow === URGENT_WORKFLOW_RUN;
  return false;
}

// git diff --quiet exit codes: 0 = no diff, 1 = diff, anything else = error.
function classifyDiffExit(code) {
  if (code === 0) return 'clean';
  if (code === 1) return 'dirty';
  return 'error';
}

/**
 * Pure decision function — the only place skip/proceed logic lives.
 * @param {object} i
 * @param {string} i.eventName     schedule | workflow_dispatch | workflow_run
 * @param {boolean} i.gateDisabled kill switch
 * @param {string|null} i.baselineSha  live READY prod deployment SHA (null = unknown)
 * @param {number|null} i.deployAgeSec age of that deployment (null = unknown)
 * @param {string} i.headSha
 * @param {'clean'|'dirty'|'error'|null} i.diffResult site-path diff vs baseline
 * @param {'clean'|'dirty'|'error'|null} i.dataDiffResult core-data (reviews.json
 *   + shows.json) blob-SHA diff vs the SHAs stamped on the live deployment —
 *   see BRO-3149 header comment. An unresolved value ('error'/null — lookup
 *   unavailable) never forces a SKIP by itself: in the schedule branch it
 *   falls through to the site-path signal (with an age-gated staleness
 *   backstop as the fallback bound); in the non-schedule already-live dedup
 *   branch it fails OPEN (proceeds) rather than silently dedup-skipping a
 *   possible real core-data change — those are deliberately different because
 *   only the schedule branch has a staleness backstop to fall back on.
 * @param {number} [i.minIntervalSec] BRO-8028 routine throttle (0 = off)
 * @param {number} [i.backstopSec] staleness backstop (BRO-8198, default 3h)
 * @returns {{proceed: boolean, reason: string}}
 */
function decide({ eventName, gateDisabled, baselineSha, deployAgeSec, headSha, diffResult, dataDiffResult, codeDiffResult = null, minIntervalSec = 0, backstopSec = DEFAULT_STALENESS_BACKSTOP_SEC }) {
  if (gateDisabled) return { proceed: true, reason: 'kill-switch' };

  if (eventName !== 'schedule') {
    // Explicit ship intent — dedup only when this exact SHA is verifiably live
    // (strictly less skip-prone than the old gh-run-list dedup, which skipped
    // against SHAs of runs that never deployed) AND core data is POSITIVELY
    // known to have not advanced (BRO-3149 — a rebuild that changed ONLY
    // private core-data without moving public HEAD used to dedup here even
    // though a redeploy would ship fresher data). An UNKNOWN data signal
    // ('error'/null — e.g. a transient GitHub API failure) fails OPEN here
    // rather than silently dedup-skipping, unlike the schedule branch below
    // (which has an age-gated staleness backstop to fall back on instead):
    // this is the workflow_run lane rebuild-fast.yml's direct post-push
    // dispatch uses — the highest-value trigger for exactly the bug class
    // this file exists to close (Codex adversarial /code-review, BRO-3149).
    if (baselineSha && baselineSha === headSha) {
      if (dataDiffResult === 'clean') return { proceed: false, reason: 'already-live' };
      return { proceed: true, reason: dataDiffResult === 'dirty' ? 'data-changed' : 'data-unknown-fail-open' };
    }
    return { proceed: true, reason: 'explicit-ship' };
  }

  if (!baselineSha) return { proceed: true, reason: 'no-baseline-fail-open' };
  // BRO-8028 min-interval throttle (routine triggers only; see header). Unknown
  // age fails open below; a code-path diff that is dirty OR unknown ships.
  if (minIntervalSec > 0 && deployAgeSec != null && deployAgeSec < minIntervalSec) {
    if (baselineSha !== headSha && codeDiffResult !== 'clean') return { proceed: true, reason: 'code-changed' };
    return { proceed: false, reason: 'min-interval' };
  }
  if (baselineSha === headSha) {
    if (dataDiffResult === 'dirty') return { proceed: true, reason: 'data-changed' };
    // dataDiffResult is 'clean'/'error'/null here. A positively-clean data
    // signal is a genuine no-op — skip immediately (matches pre-BRO-3149
    // behavior for this branch, which had no second signal at all). An
    // UNKNOWN data signal (error/null — e.g. a transient API failure or a
    // missing token) must NOT silently swallow the staleness backstop: an
    // idle public repo (baselineSha === headSha can persist for a while in a
    // quiet window) combined with a persistently-broken data lookup would
    // otherwise strand core-data staleness indefinitely, since this branch
    // used to return before the age check ever ran (Codex adversarial
    // review, BRO-3149). Still requires deployAgeSec to be known and past
    // the backstop — an unknown age alone doesn't force a proceed here,
    // consistent with the "positive proof only" skip philosophy in the
    // header comment.
    // BRO-8198: a positively-clean data signal no longer skips past the
    // backstop either. 'clean' covers only DATA_TRACKED_FILES; untracked site
    // data (audience-buzz.json) changes without moving HEAD, so the old
    // clean-and-stale skip left it stale with no bound (Codex ship-check).
    // 7-day replay: no same-HEAD skip happened past 3h, so this adds ~0 builds.
    if (deployAgeSec != null && deployAgeSec > backstopSec) {
      return { proceed: true, reason: 'staleness-backstop' };
    }
    return { proceed: false, reason: 'no-new-commits' };
  }
  if (deployAgeSec == null) return { proceed: true, reason: 'no-age-fail-open' };
  if (deployAgeSec > backstopSec) return { proceed: true, reason: 'staleness-backstop' };
  if (diffResult === 'dirty') return { proceed: true, reason: 'content-changed' };
  if (dataDiffResult === 'dirty') return { proceed: true, reason: 'data-changed' };
  if (diffResult === 'clean') return { proceed: false, reason: 'content-gate' };
  return { proceed: true, reason: 'diff-error-fail-open' };
}

/**
 * Pure: parse a numeric repo variable. GitHub passes an unset `vars.X` as ''.
 * Empty/blank -> default (not a warning). Anything that is not a plain decimal
 * ('6h', '0x6', '1e3') -> default + invalid, so main() can warn instead of the
 * kill switch silently doing nothing. Out of range -> clamped + flagged.
 */
function resolveEnvNumber(raw, { def, min, max }) {
  const t = raw == null ? '' : String(raw).trim();
  if (t === '') return { value: def, invalid: false, clamped: false };
  if (!/^\d+(\.\d+)?$/.test(t)) return { value: def, invalid: true, clamped: false };
  const n = Number(t);
  if (n < min) return { value: min, invalid: false, clamped: true };
  if (n > max) return { value: max, invalid: false, clamped: true };
  return { value: n, invalid: false, clamped: false };
}

/** Pure: the gate's two timing knobs from env (GATE_MIN_INTERVAL_MIN, GATE_BACKSTOP_MIN). */
function resolveGateTiming(env) {
  const warnings = [];
  const note = (name, r, raw) => {
    if (r.invalid) warnings.push(`${name}='${raw}' is not a number of minutes; using default ${r.value}`);
    else if (r.clamped) warnings.push(`${name}='${raw}' is out of range; clamped to ${r.value}`);
  };
  const mi = resolveEnvNumber(env.GATE_MIN_INTERVAL_MIN, { def: DEFAULT_MIN_INTERVAL_MIN, min: 0, max: 720 });
  note('GATE_MIN_INTERVAL_MIN', mi, env.GATE_MIN_INTERVAL_MIN);
  const bs = resolveEnvNumber(env.GATE_BACKSTOP_MIN, { def: DEFAULT_STALENESS_BACKSTOP_MIN, min: 60, max: 1440 });
  note('GATE_BACKSTOP_MIN', bs, env.GATE_BACKSTOP_MIN);
  const minIntervalSec = mi.value * 60;
  let backstopSec = bs.value * 60;
  if (minIntervalSec > 0 && backstopSec < minIntervalSec + BACKSTOP_OVER_INTERVAL_MARGIN_SEC) {
    backstopSec = minIntervalSec + BACKSTOP_OVER_INTERVAL_MARGIN_SEC;
    warnings.push(`backstop ${bs.value}m is not above the min interval ${mi.value}m; using ${backstopSec / 60}m`);
  }
  return { minIntervalSec, backstopSec, warnings };
}

/** Pure: does the site diff matter? Past the backstop decide() proceeds without it. Mirrors decide()'s `>`. */
function diffWindowOpen(deployAgeSec, backstopSec) {
  return deployAgeSec != null && deployAgeSec <= backstopSec;
}

/**
 * Pure: health-check.js deploy-freshness thresholds. A quiet night where public
 * HEAD does not move and tracked data is clean skips without an age check, and
 * GitHub delays crons by hours, so the alert sits well past the backstop:
 * warn at backstop+5h, error at backstop+9h (3h -> 8h/12h, today's values).
 */
function freshnessAlertHours(backstopSec) {
  const b = backstopSec / 3600;
  return { warnH: b + 5, errorH: b + 9 };
}

