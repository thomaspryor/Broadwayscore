/**
 * Task-store archiver — moves long-completed tasks AND stale in_progress
 * orphans out of the live ~/.claude/tasks/<list>/ directory into a sibling
 * archive/ subdirectory, so the harness's injected task-list reminder (one
 * line per file in the live directory, ~860 lines / avg 16x per session per
 * the 5-day audit) shrinks to just pending/active/recently-completed work.
 *
 * ID-COLLISION SAFETY (card #854 design review P0): the harness's own
 * next-id allocator (mirrored in notion-tasks-sync.js's nextId()) computes
 * `Math.max(highwatermark, maxFileIdInLiveDir + 1)`. Live-tested against
 * the real store 2026-08-02: creating a task, then removing that exact
 * task's file, then creating another task reused the freed id — the
 * highwatermark file lags behind live creations and does not by itself
 * prevent reuse. Removing a file that WAS the live directory's max id is
 * therefore unsafe. selectArchivable() guards this by refusing to select
 * any of the `keepTopN` highest-id files present, regardless of age or
 * status.
 *
 * DEFAULT_KEEP_TOP_N=50 was never load-bearing at that value (card #1410
 * proof): the frontier Set (lines below) is built from the byId-descending
 * slice of the CURRENT scan, so at any keepTopN>=1 the single highest-id
 * live file is always excluded from every archival run — the maxFile scan
 * nextId() depends on therefore returns the same answer regardless of how
 * low keepTopN is, as long as it stays >=1. highwatermark only ever moves
 * forward (writeHwm takes Math.max). 50 was originally justified by "archive
 * candidates are always far below the frontier in practice" — true only
 * while completed/stale-in_progress were the sole populations; card #1351
 * added pending-task archival, including the "BSC Daily:" digest family,
 * which land AT the frontier by construction (freshly created every day) and
 * were therefore permanently unarchivable under 50. Lowered to 1 (the
 * minimum the invariant above actually requires) so pending/BSC-Daily
 * archival works without reopening the id-collision hole 50 existed to
 * close.
 *
 * Task JSON carries no completion timestamp (checked: real corpus has
 * none), so "completed >24h ago" is judged off the file's own mtime — the
 * last write is the status flip to completed in the overwhelming common
 * case. Same reasoning applies to "in_progress, untouched >7d": mtime is
 * the last status-flip-to-in_progress or owner-claim write.
 *
 * Card #955 (token-cost hunt round 2): threshold tightened 48h -> 24h for
 * completed tasks, and a second population (stale in_progress orphans —
 * sessions that died without ever flipping status) added. Both keep the
 * S1 union-loader contract: archived tasks remain point-lookupable via
 * readArchivedTask()/mergeWithArchive() from bsc-next.js,
 * notion-tasks-sync.js, and workspace-mark-done.js.
 *
 * Card #1351: pending tasks never aged out regardless of age — a 2026-08-12
 * audit found 389 open cards (0 archivable under the rules above) being
 * injected into every TaskList-adjacent reminder (~9K tokens each, 6x in one
 * session). Two more populations added, both still gated by the keepTopN
 * id-collision frontier:
 *   3. pending tasks untouched beyond pendingMaxAgeMs (default 30d).
 *   4. "BSC Daily:"-titled pending tasks (auto-generated by the morning
 *      digest, regenerated daily regardless of whether the prior day's card
 *      was archived) on a much shorter clock, bscDailyMaxAgeMs (default
 *      7d) — pure noise in the injected list once stale.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const DEFAULT_MAX_AGE_MS = 24 * 60 * 60 * 1000; // tightened from 48h — card #955, hunt item 1
const DEFAULT_KEEP_TOP_N = 1; // minimum the id-collision invariant requires — card #1410, see module docstring
const DEFAULT_STALE_IN_PROGRESS_MS = 7 * 24 * 60 * 60 * 1000; // 7 days untouched
const DEFAULT_PENDING_MAX_AGE_MS = 30 * 24 * 60 * 60 * 1000; // 30 days untouched — card #1351
const DEFAULT_BSC_DAILY_MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000; // 7 days — card #1351, digest regenerates these daily
const BSC_DAILY_TITLE_RE = /^BSC Daily:/;
/**
 * Pure selection: which tasks are safe + eligible to archive.
 *
 * Four independent populations are eligible, unioned:
 *   1. completed tasks older than maxAgeMs (the original S1 #854 lever).
 *   2. in_progress tasks untouched for longer than staleInProgressMs — the
 *      dispatching session died or was abandoned without ever flipping
 *      status (card #955 hunt item 1). `owner` is NOT used as a signal:
 *      empirically most in_progress tasks never get an owner set (102/107 on
 *      2026-08-03), so absence of owner is not evidence of staleness.
 *   3. pending tasks untouched for longer than pendingMaxAgeMs (card
 *      #1351) — pending tasks previously never aged out at all, so the
 *      live directory only ever grew.
 *   4. pending tasks whose subject starts with "BSC Daily:" (the morning
 *      digest's auto-generated alert-card family) untouched for longer than
 *      bscDailyMaxAgeMs — a much shorter clock than population 3, since the
 *      digest regenerates a fresh card daily regardless of whether the
 *      prior one archived (card #1351).
 *
 * THE DEADLOCK, and why population 2 stays but is RELABELLED on the way in.
 * Measured 2026-08-12: 86 of 875 archived tasks sat in archive/ with status
 * still `in_progress`, unreachable forever. Mechanism:
 *   - this archiver moved an in_progress task to archive/ after 7d untouched,
 *     with its status untouched;
 *   - the only thing that flips such a task back to pending is
 *     sweepUntrackedInProgress (bsc-reconcile.js:478-610), which reads the
 *     LIVE dir only — bscNext.loadTasks is live-dir-only by deliberate design
 *     (card #854 docstring, bsc-next.js:84-95).
 * So surviving 7 days in_progress made a task PERMANENTLY in_progress:
 * invisible to --list/actionable(), dispatchable only by explicit --id.
 *
 * The fix is to stop the ARCHIVED COPY from lying, not to stop archiving.
 * archiveCompletedTasks writes the archive copy with status 'pending' (and
 * owner cleared) for this population, and never rewrites the live file — the
 * live file is only unlinked, exactly as before. That matters: an earlier
 * version of this fix flipped LIVE files to pending instead, which
 * reimplemented sweepUntrackedInProgress's flip while dropping every one of
 * its guards (live-lease check, cmux-tab match, Notion idle check, the
 * has-completed-Outcome park that exists because reopening a finished card
 * redid finished work twice, and a 10-flip-per-sweep cap). Keying a LIVE flip
 * on task-file mtime alone is unsafe — bsc-next.js:807 documents that a
 * genuinely alive session doing long batch work does not write to its task
 * file, and bsc-prune.js:258-269 re-dispatches a pending task whose tab looks
 * dead. Relabelling only the archived copy needs none of those guards, because
 * nothing in the live pool changes and no dispatcher can pick an archived task
 * up. Returning archived work to the pool is a separate, deliberate act.
 *
 * @param {Array<{id: string, status: string, mtimeMs: number, subject?: string}>} tasks
 * @param {object} opts
 * @param {number} opts.now - Date.now()-equivalent, injected for testability
 * @param {number} [opts.maxAgeMs]
 * @param {number} [opts.keepTopN]
 * @param {number} [opts.staleInProgressMs] - set to Infinity to disable population 2
 * @param {number} [opts.pendingMaxAgeMs] - set to Infinity to disable this population
 * @param {number} [opts.bscDailyMaxAgeMs] - set to Infinity to disable this population
 * @returns {string[]} ids selected for archival, ascending
 */
function selectArchivable(tasks, {
  now, maxAgeMs = DEFAULT_MAX_AGE_MS, keepTopN = DEFAULT_KEEP_TOP_N,
  staleInProgressMs = DEFAULT_STALE_IN_PROGRESS_MS,
  pendingMaxAgeMs = DEFAULT_PENDING_MAX_AGE_MS,
  bscDailyMaxAgeMs = DEFAULT_BSC_DAILY_MAX_AGE_MS,
}) {
  const byIdDesc = [...tasks].sort((a, b) => parseInt(b.id, 10) - parseInt(a.id, 10));
  const frontier = new Set(byIdDesc.slice(0, keepTopN).map((t) => t.id));
  const eligible = (t) => {
    if (frontier.has(t.id)) return false;
    if (typeof t.mtimeMs !== 'number') return false;
    if (t.status === 'completed') return now - t.mtimeMs > maxAgeMs;
    if (t.status === 'in_progress') return now - t.mtimeMs > staleInProgressMs;
    if (t.status === 'pending') {
      const isBscDaily = typeof t.subject === 'string' && BSC_DAILY_TITLE_RE.test(t.subject);
      return now - t.mtimeMs > (isBscDaily ? bscDailyMaxAgeMs : pendingMaxAgeMs);
    }
    return false;
  };
  return tasks
    .filter(eligible)
    .map((t) => t.id)
    .sort((a, b) => parseInt(a, 10) - parseInt(b, 10));
}

/**
 * Pure: the archive copy to write for a task being filed away.
 *
 * For every status but `in_progress` this is the task verbatim — archival has
 * always been a byte-for-byte move and stays one. For `in_progress` it returns
 * a relabelled copy: status 'pending', owner cleared, plus breadcrumbs saying a
 * timer did it. That single substitution is the whole deadlock fix (see
 * selectArchivable): the archived record stops claiming work is underway when
 * the claiming session is long gone, so anything that later reads archive/
 * (mergeWithArchive, the recovery audit, a future sweep) sees the truth.
 *
 * `owner` is cleared to match sweepUntrackedInProgress's flipFn, which nulls it
 * for the same reason: a non-in_progress task still naming a vanished session
 * as owner misreports who holds it.
 *
 * Pure and exported so the test asserts the real substitution, and so callers
 * can preview it without writing anything.
 *
 * @param {object} task - parsed task JSON as found on disk
 * @param {object} opts
 * @param {number} opts.now - Date.now()-equivalent
 * @param {number} [opts.idleMs] - how long it had been untouched, for the reason string
 * @returns {{ task: object, relabelled: boolean }}
 */
function archiveCopyFor(task, { now, idleMs = null } = {}) {
  if (!task || task.status !== 'in_progress') return { task, relabelled: false };
  const days = typeof idleMs === 'number' ? Math.floor(idleMs / (24 * 60 * 60 * 1000)) : null;
  return {
    relabelled: true,
    task: {
      ...task,
      status: 'pending',
      owner: null,
      archivedFromInProgressAt: new Date(now).toISOString(),
      archivedFromInProgressReason: days == null
        ? 'archived while in_progress with no activity — the claiming session died without flipping status'
        : `no activity for ${days}d while in_progress — the claiming session died without flipping status`,
    },
  };
}

/** Load every `<id>.json` in dir with its parsed content + mtime. Skips unparseable files. */
function loadTasksWithMtime(dir) {
  let files;
  try { files = fs.readdirSync(dir); } catch { return []; }
  const out = [];
  for (const f of files) {
    if (!/^\d+\.json$/.test(f)) continue;
    const p = path.join(dir, f);
    let stat, data;
    try { stat = fs.statSync(p); } catch { continue; }
    try { data = JSON.parse(fs.readFileSync(p, 'utf8')); } catch { continue; }
    if (!data || typeof data !== 'object') continue;
    out.push({ ...data, mtimeMs: stat.mtimeMs });
  }
  return out;
}

// Minimal mkdir-based advisory lock, mirroring json-write-guard.js's
// acquireLock/releaseLock shape (not imported — that module is scoped to
// single-file JSON writes with a snapshot/merge contract this directory
// archiver doesn't need; duplicating the small lock primitive is cheaper
// and safer than bolting an unrelated shape onto a shared file).
// Advisory only: it serializes concurrent runs of THIS script, not the
// harness's own TaskCreate/TaskUpdate — those are protected by never
// touching the id frontier (see selectArchivable) and by the archive-then-
// delete ordering in archiveCompletedTasks below.
const LOCK_STALE_MS = 5 * 60 * 1000;

function acquireArchiveLock(dir) {
  const lockDir = path.join(dir, '.archive-lock');
  const ownerPath = path.join(lockDir, 'owner.json');
  const deadline = Date.now() + 30_000;
  for (;;) {
    try {
      fs.mkdirSync(lockDir);
      fs.writeFileSync(ownerPath, JSON.stringify({ pid: process.pid, acquiredAt: new Date().toISOString() }));
      return () => { try { fs.rmSync(lockDir, { recursive: true, force: true }); } catch { /* best-effort */ } };
    } catch (err) {
      if (err.code !== 'EEXIST') throw err;
      let stale = false;
      try {
        const owner = JSON.parse(fs.readFileSync(ownerPath, 'utf8'));
        stale = Date.now() - Date.parse(owner.acquiredAt) > LOCK_STALE_MS;
      } catch { stale = true; } // unreadable owner.json — a crashed writer, not a live one
      if (stale) { try { fs.rmSync(lockDir, { recursive: true, force: true }); } catch { /* retry loop handles it */ } continue; }
      if (Date.now() > deadline) throw new Error(`task-store-archive: timed out waiting for lock at ${lockDir}`);
    }
  }
}

/**
 * Archive selected ids: write full content to archive/<id>.json (verified
 * by read-back), THEN delete the live copy. Never deletes before the
 * archive copy is confirmed on disk, so a crash mid-run leaves a task
 * live-and-duplicated (harmless — the union loaders in bsc-next.js /
 * workspace-mark-done.js / notion-tasks-sync.js dedupe by id, live wins)
 * rather than lost.
 *
 * @param {string} dir - live tasks directory (~/.claude/tasks/<list>)
 * @param {object} [opts] - forwarded to selectArchivable; opts.now required by caller for determinism
 * @returns {{archived: string[], skipped: Array<{id:string, reason:string}>, bytesFreed: number}}
 */
function archiveCompletedTasks(dir, opts = {}) {
  const now = opts.now ?? Date.now();
  const release = acquireArchiveLock(dir);
  try {
    const tasks = loadTasksWithMtime(dir);
    const ids = selectArchivable(tasks, { ...opts, now });
    const archiveDir = path.join(dir, 'archive');
    if (ids.length && !fs.existsSync(archiveDir)) fs.mkdirSync(archiveDir, { recursive: true });

    const archived = [];
    const skipped = [];
    const relabelled = [];
    let bytesFreed = 0;

    for (const id of ids) {
      const livePath = path.join(dir, `${id}.json`);
      const archivePath = path.join(archiveDir, `${id}.json`);
      let raw;
      try { raw = fs.readFileSync(livePath, 'utf8'); } catch { skipped.push({ id, reason: 'live file vanished mid-run' }); continue; }
      // Re-verify right before moving — a concurrent TaskUpdate could have
      // reopened this task (status) or, for the in_progress population,
      // resumed active work on it (mtime) between the initial scan and now.
      let parsed, liveStat;
      try { parsed = JSON.parse(raw); } catch { skipped.push({ id, reason: 'unparseable at move time' }); continue; }
      if (!['completed', 'in_progress', 'pending'].includes(parsed.status)) { skipped.push({ id, reason: `status changed to ${parsed.status}` }); continue; }
      if (parsed.status === 'in_progress') {
        try { liveStat = fs.statSync(livePath); } catch { skipped.push({ id, reason: 'live file vanished mid-run' }); continue; }
        const staleMs = opts.staleInProgressMs ?? DEFAULT_STALE_IN_PROGRESS_MS;
        if (now - liveStat.mtimeMs <= staleMs) { skipped.push({ id, reason: 'in_progress task touched again since scan — no longer stale' }); continue; }
      }
      if (parsed.status === 'pending') {
        try { liveStat = fs.statSync(livePath); } catch { skipped.push({ id, reason: 'live file vanished mid-run' }); continue; }
        const isBscDaily = typeof parsed.subject === 'string' && BSC_DAILY_TITLE_RE.test(parsed.subject);
        const staleMs = isBscDaily
          ? (opts.bscDailyMaxAgeMs ?? DEFAULT_BSC_DAILY_MAX_AGE_MS)
          : (opts.pendingMaxAgeMs ?? DEFAULT_PENDING_MAX_AGE_MS);
        if (now - liveStat.mtimeMs <= staleMs) { skipped.push({ id, reason: 'pending task touched again since scan — no longer stale' }); continue; }
      }

      // THE DEADLOCK FIX: for the in_progress population the archive copy is
      // relabelled to pending (owner cleared) so the filed record stops
      // claiming work is underway. Every other status is still archived
      // byte-for-byte. The LIVE file is never rewritten — only unlinked below,
      // exactly as before — which is why this needs none of
      // sweepUntrackedInProgress's live-flip guards.
      const idleMs = liveStat ? now - liveStat.mtimeMs : null;
      const { task: archiveTask, relabelled: wasRelabelled } = archiveCopyFor(parsed, { now, idleMs });
      const body = wasRelabelled ? `${JSON.stringify(archiveTask, null, 2)}\n` : raw;
      const tmp = `${archivePath}.tmp-${crypto.randomBytes(4).toString('hex')}`;
      fs.writeFileSync(tmp, body);
      fs.renameSync(tmp, archivePath);
      const readBack = fs.readFileSync(archivePath, 'utf8');
      if (readBack !== body) { skipped.push({ id, reason: 'archive read-back mismatch — live copy kept' }); continue; }
      if (wasRelabelled) relabelled.push(id);

      const sizeBefore = fs.statSync(livePath).size;
      fs.unlinkSync(livePath);
      bytesFreed += sizeBefore;
      archived.push(id);
    }
    return { archived, relabelled, skipped, bytesFreed };
  } finally {
    release();
  }
}

/** Read a single archived task by id, or null. Cheap point lookup — no directory scan. */
function readArchivedTask(dir, id) {
  try { return JSON.parse(fs.readFileSync(path.join(dir, 'archive', `${id}.json`), 'utf8')); }
  catch { return null; }
}

/**
 * Merge a live-dir task array with every task under archive/, live wins on
 * id collision (shouldn't happen — archival deletes the live copy — but a
 * crash-interrupted run per archiveCompletedTasks's docstring can leave
 * both, and live is always the freshest). Shared by bsc-next.js and
 * notion-tasks-sync.js (same repo, same directory contract); workspace-
 * mark-done.js (~/.claude/hooks, a separate repo) duplicates this
 * intentionally rather than cross-repo-require — same precedent as
 * AUTO_PROJECTS/cleanTitle already documented there.
 */
function mergeWithArchive(dir, liveTasks) {
  const archiveDir = path.join(dir, 'archive');
  let archiveFiles;
  try { archiveFiles = fs.readdirSync(archiveDir); } catch { return liveTasks; }
  const liveIds = new Set(liveTasks.map((t) => t.id));
  const archived = archiveFiles
    .filter((f) => /^\d+\.json$/.test(f))
    .map((f) => { try { return JSON.parse(fs.readFileSync(path.join(archiveDir, f), 'utf8')); } catch { return null; } })
    .filter(Boolean)
    .filter((t) => !liveIds.has(t.id));
  return [...liveTasks, ...archived];
}

