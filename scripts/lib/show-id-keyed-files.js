const REPOS = ['web', 'core-data', 'review-texts'];
const SHAPES = ['map', 'records', 'list', 'id-values', 'dir', 'file'];

/** Entries for one repo. */
function entriesForRepo(repo) {
  return SHOW_ID_KEYED_FILES.filter((e) => e.repo === repo);
}

/**
 * Structural self-check (the colocated test runs it): every entry names a
 * known repo and shape, map/records/list/id-values carry a keyPath, records
 * carry an idField, file entries carry a `{id}` pattern.
 * @returns {string[]} problems (empty when the registry is well-formed)
 */
function validateRegistry(entries = SHOW_ID_KEYED_FILES) {
  const problems = [];
  entries.forEach((e, i) => {
    const where = `entry ${i} (${e.repo}:${e.path})`;
    if (!REPOS.includes(e.repo)) problems.push(`${where}: unknown repo ${e.repo}`);
    if (!SHAPES.includes(e.shape)) problems.push(`${where}: unknown shape ${e.shape}`);
    if (typeof e.path !== 'string' || !e.path) problems.push(`${where}: missing path`);
    if (['map', 'records', 'list', 'id-values'].includes(e.shape) && !Array.isArray(e.keyPath)) {
      problems.push(`${where}: ${e.shape} needs a keyPath array`);
    }
    if (e.shape === 'records' && !e.idField) problems.push(`${where}: records needs idField`);
    if (e.shape === 'file' && !(typeof e.pattern === 'string' && e.pattern.includes('{id}'))) {
      problems.push(`${where}: file needs a pattern containing {id}`);
    }
    if (e.keyedBy && !['id', 'slug'].includes(e.keyedBy)) problems.push(`${where}: keyedBy must be id|slug`);
    if (e.keyStyle && !['exact', 'colon-segments'].includes(e.keyStyle)) problems.push(`${where}: bad keyStyle`);
    if (e.writeGuard && !['shows', 'commercial', 'audience-buzz', 'review', 'atomic'].includes(e.writeGuard)) {
      problems.push(`${where}: bad writeGuard ${e.writeGuard}`);
    }
  });
  return problems;
}

module.exports = { SHOW_ID_KEYED_FILES, REPOS, SHAPES, entriesForRepo, validateRegistry };
