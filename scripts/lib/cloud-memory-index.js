#!/usr/bin/env node
// scripts/lib/cloud-memory-index.js — uncapped one-line-per-note index of the
// cloud-memory/ mirror, written to cloud-memory/INDEX.txt.
//
// WHY THIS EXISTS (BRO-2556)
// --------------------------
// MEMORY.md is hook-capped at 180 lines, so it can only point at a curated
// subset of the ~700 notes. Locally that is fine: the harness recalls from the
// live memory dir by description. A cloud session has no recall tool; the
// index it reads IS its retrieval mechanism, so every note MEMORY.md does not
// name was invisible to it. INDEX.txt lists every root-level note with its
// type and description, so `grep -i <topic> cloud-memory/INDEX.txt` finds it.
//
// The file is deliberately NOT .md: cloud-memory-merge.js hashDir() and
// cloud-memory-reconcile.js isNote() only see root-level *.md, so the index is
// never adopted into the Mac's memory dir as a bogus note and never deleted by
// the merge. It is regenerated as its own step by scripts/sync-memory-to-repo.sh
// (Mac session-stop) and .github/workflows/cloud-memory-reconcile.yml (CI,
// every 6h). .gitattributes marks it merge=union so two writers never make a
// land rebase conflict; the next regeneration drops any duplicate line.
//
// Dependency-free on purpose: the reconcile workflow runs no `npm ci`.
// Pure functions (parseNoteFrontmatter, indexLine, buildIndex) + I/O wrapper
// (writeIndex), per CLAUDE.md rule 15. Tests: scripts/lib/cloud-memory-index.test.mjs.

'use strict';

const fs = require('fs');
const path = require('path');

const INDEX_BASENAME = 'INDEX.txt';
const DESCRIPTION_MAX = 300;
// The one header line. Starts with '#' so it is easy to skip, and says nothing
// a topic grep would plausibly match.
const HEADER = '# file | type | description (generated by scripts/lib/cloud-memory-index.js; do not edit)';

function unquote(raw) {
  const val = raw.trim();
  if (val.length >= 2 && val.startsWith('"') && val.endsWith('"')) {
    try { return JSON.parse(val); } catch { return val.slice(1, -1); }
  }
  if (val.length >= 2 && val.startsWith("'") && val.endsWith("'")) {
    return val.slice(1, -1).replace(/''/g, "'");
  }
  return val;
}

/**
 * Read the leading `---` YAML block of a note. Flat `key: value` lines only,
 * plus one level of nesting (about half the notes keep `type` under
 * `metadata:`); a nested key never overrides a top-level one.
 * Returns { name, description, type, archived, body }.
 */
function parseNoteFrontmatter(text) {
  const out = { name: '', description: '', type: '', archived: false, body: text };
  const normalized = text.replace(/\r\n/g, '\n');
  if (!normalized.startsWith('---\n')) return out;
  // Search from index 3 so an empty block (`---\n---`) closes at once
  // instead of swallowing the body up to its first horizontal rule.
  const end = normalized.indexOf('\n---', 3);
  if (end === -1) return out;
  // A closing `---` on the last line (no newline after it) leaves no body.
  const bodyStart = normalized.indexOf('\n', end + 1);
  out.body = bodyStart === -1 ? '' : normalized.slice(bodyStart + 1);
  const top = {};
  const nested = {};
  let blockIndent = -1; // indent of a block-scalar key whose lines we are skipping
  for (const line of normalized.slice(4, end).split('\n')) {
    const indent = line.match(/^\s*/)[0].length;
    // Lines of a block scalar are more indented than its key: prose, not keys.
    if (blockIndent >= 0) {
      if (!line.trim() || indent > blockIndent) continue;
      blockIndent = -1;
    }
    const m = line.match(/^(\s*)([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!m || m[3] === '') continue;
    // A block scalar (`description: >`, `|-2`, `> # note`) continues on lines
    // this flat reader does not follow; leave it empty so the name/heading
    // fallback applies.
    if (/^[>|](?:[-+]?\d?|\d[-+])?(?:\s+#.*)?$/.test(m[3].trim())) { blockIndent = indent; continue; }
    const target = m[1].length ? nested : top;
    if (!(m[2] in target)) target[m[2]] = unquote(m[3]);
  }
  const pick = (k) => (top[k] !== undefined ? top[k] : nested[k]) || '';
  out.name = pick('name');
  out.description = pick('description');
  out.type = pick('type');
  out.archived = String(pick('archived')).toLowerCase() === 'true';
  return out;
}

/** First markdown heading or non-empty line, for notes with no frontmatter. */
function fallbackSummary(body) {
  for (const line of body.split('\n')) {
    const t = line.replace(/^#+\s*/, '').trim();
    if (t && t !== '---') return t;
  }
  return '';
}

function oneLine(s) {
  const flat = String(s).replace(/\s+/g, ' ').replace(/\|/g, '/').trim();
  // Code points, not UTF-16 units, so a cut never splits an emoji's surrogate pair.
  const chars = Array.from(flat);
  return chars.length > DESCRIPTION_MAX ? `${chars.slice(0, DESCRIPTION_MAX - 3).join('').trimEnd()}...` : flat;
}

/** One index line for one note: `file | type | description`. */
function indexLine(file, text) {
  const fm = parseNoteFrontmatter(text);
  const summary = fm.description || fm.name || fallbackSummary(fm.body) || '(no description)';
  const type = (fm.type || '-') + (fm.archived ? ' [archived]' : '');
  return `${file} | ${oneLine(type)} | ${oneLine(summary)}`;
}

/** The root-level note filter cloud-memory-merge.js hashDir() uses, minus the curated index. */
function isIndexedNote(name) {
  return name.endsWith('.md') && !name.startsWith('.') && name !== 'MEMORY.md';
}

/** entries: [{ file, text }] → full INDEX.txt content (byte-stable: sorted, no timestamp). */
function buildIndex(entries) {
  const lines = entries
    .filter((e) => isIndexedNote(e.file))
    .sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0))
    .map((e) => indexLine(e.file, e.text));
  return `${HEADER}\n${lines.join('\n')}\n`;
}

/** Regenerate `dir`/INDEX.txt. Writes only when the content changed. */
function writeIndex(dir, outPath = path.join(dir, INDEX_BASENAME)) {
  const entries = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!ent.isFile() || !isIndexedNote(ent.name)) continue;
    entries.push({ file: ent.name, text: fs.readFileSync(path.join(dir, ent.name), 'utf8') });
  }
  const content = buildIndex(entries);
  let current = null;
  try { current = fs.readFileSync(outPath, 'utf8'); } catch { /* first run */ }
  if (current === content) return { written: false, count: entries.length, outPath };
  fs.writeFileSync(outPath, content);
  return { written: true, count: entries.length, outPath };
}

module.exports = {
  INDEX_BASENAME, HEADER, DESCRIPTION_MAX,
  parseNoteFrontmatter, indexLine, isIndexedNote, buildIndex, writeIndex,
};

// CLI: node scripts/lib/cloud-memory-index.js [dir=cloud-memory]
if (require.main === module) {
  const dir = path.resolve(process.argv[2] || 'cloud-memory');
  const r = writeIndex(dir);
  console.error(`cloud-memory-index: ${r.written ? 'wrote' : 'unchanged'} ${path.relative(process.cwd(), r.outPath)} (${r.count} notes)`);
}
