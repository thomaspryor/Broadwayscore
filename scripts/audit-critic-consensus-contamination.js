#!/usr/bin/env node
/**
 * Audit data/critic-consensus.json for stale/contaminated consensus summaries.
 *
 * Background: scripts/generate-critic-consensus.js feeds OUR scored reviews
 * to Claude Sonnet to produce a 1-2 sentence editorial summary. Because the
 * input is our own data (not external SERP), the wrong-source contamination
 * risk is lower than the cast/commercial/audience-buzz cases — but the
 * regeneration trigger logic is also looser, so stale entries (consensus
 * generated when N reviews existed, now reviews.json has N+15 with different
 * mean) can persist quietly. This audit catches those plus orphans.
 *
 * Companion to scripts/audit-cast-contamination.js. See Notion
 * 36a637c5-416f-81b7-a72b-f7e0dfbb24fc.
 *
 * Usage:
 *   node scripts/audit-critic-consensus-contamination.js          # human report
 *   node scripts/audit-critic-consensus-contamination.js --json
 *   node scripts/audit-critic-consensus-contamination.js --strict # warn = fail
 *
 * Signals:
 *   SHOW_NOT_IN_DB        (fail) — key not present in shows.json
 *   REVIEWCOUNT_DRIFT     (fail) — |consensus.reviewCount − reviews.json count| >= 10
 *                                    (consensus is summarising a stale review set)
 *   MEANSCORE_DRIFT       (fail) — |consensus.meanScore − reviews.json mean| >= 15
 *                                    (consensus text reflects an outdated critical mood)
 *
 * Thresholds chosen against live data (2026-05-24, 941 consensus records):
 *   - REVIEWCOUNT_DRIFT >=10: 0 baseline hits
 *   - MEANSCORE_DRIFT >=15: 0 baseline hits
 *   - Both are conservatively above the live drift maxima so a single
 *     new opening night surfacing 11+ reviews would fire, prompting the
 *     consensus to be regenerated by `update-critic-consensus.yml`.
 *
 * NOT included: text-token scanning for "wrong show mentioned". A naive
 * >=4-char token match against other shows in shows.json fires on
 * ~every record (generic words like "musical"/"come" match many titles),
 * so it's deliberately out of scope; the drift signals are the more
 * reliable contamination indicator for this file.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONSENSUS_FILE = path.join(ROOT, 'data', 'critic-consensus.json');
const SHOWS_FILE = path.join(ROOT, 'data', 'shows.json');
const REVIEWS_FILE = path.join(ROOT, 'data', 'reviews.json');

const FAIL_SIGNALS = new Set([
  'SHOW_NOT_IN_DB',
  'REVIEWCOUNT_DRIFT',
  'MEANSCORE_DRIFT',
]);

const REVIEWCOUNT_DRIFT_THRESHOLD = 10;
const MEANSCORE_DRIFT_THRESHOLD = 15;

function loadShowIds() {
  try {
    const data = JSON.parse(fs.readFileSync(SHOWS_FILE, 'utf-8'));
    return new Set((data.shows || []).map(s => s.id));
  } catch {
    return null;
  }
}

// reviews.json may be {reviews:[...]} or a bare array depending on
// snapshot age — handle both.
function loadReviewsByShow() {
  try {
    const raw = JSON.parse(fs.readFileSync(REVIEWS_FILE, 'utf-8'));
    const arr = Array.isArray(raw) ? raw : (raw.reviews || []);
    const m = new Map();
    for (const r of arr) {
      if (!r || !r.showId) continue;
      if (!m.has(r.showId)) m.set(r.showId, []);
      m.get(r.showId).push(r);
    }
    return m;
  } catch {
    return null;
  }
}

function audit() {
  const showIds = loadShowIds();
  const reviewsByShow = loadReviewsByShow();
  const raw = JSON.parse(fs.readFileSync(CONSENSUS_FILE, 'utf-8'));
  const showsMap = raw.shows || {};
  const issues = [];

  for (const [id, c] of Object.entries(showsMap)) {
    if (!c || typeof c !== 'object') continue;

    const flags = [];

    if (showIds && !showIds.has(id)) flags.push('SHOW_NOT_IN_DB');

    if (reviewsByShow) {
      const reviews = reviewsByShow.get(id);
      if (reviews) {
        const scored = reviews.filter(r => typeof r.score === 'number');
        if (scored.length > 0) {
          const actualCount = scored.length;
          const rcDiff = Math.abs((c.reviewCount || 0) - actualCount);
          if (rcDiff >= REVIEWCOUNT_DRIFT_THRESHOLD) {
            flags.push(`REVIEWCOUNT_DRIFT:consensus=${c.reviewCount || 0},actual=${actualCount},diff=${rcDiff}`);
          }

          const actualMean = scored.reduce((s, r) => s + r.score, 0) / actualCount;
          const msDiff = Math.abs((c.meanScore || 0) - actualMean);
          if (msDiff >= MEANSCORE_DRIFT_THRESHOLD) {
            flags.push(`MEANSCORE_DRIFT:consensus=${c.meanScore || 0},actual=${Math.round(actualMean)},diff=${Math.round(msDiff)}`);
          }
        }
      }
    }

    if (flags.length > 0) {
      const hasFail = flags.some(f => FAIL_SIGNALS.has(f.split(':')[0]));
      issues.push({
        id,
        text: c.text ? c.text.slice(0, 120) + (c.text.length > 120 ? '…' : '') : null,
        severity: hasFail ? 'fail' : 'warn',
        flags,
      });
    }
  }

  return issues.sort((a, b) => {
    if (a.severity !== b.severity) return a.severity === 'fail' ? -1 : 1;
    return a.id.localeCompare(b.id);
  });
}

function main() {
  const issues = audit();
  const json = process.argv.includes('--json');
  const strict = process.argv.includes('--strict');
  // --gate: per-push trunk catastrophe floor (test.yml). Of the three FAIL
  // signals only SHOW_NOT_IN_DB (a structural orphan key) is a zero-FP per-push
  // catastrophe; REVIEWCOUNT_DRIFT / MEANSCORE_DRIFT are STALENESS that fires on
  // opening nights and self-heals on the next update-critic-consensus regen, so
  // they are demoted to the digest. Decision is the pure scripts/lib/critic-
  // consensus-contamination-gate.js (CLAUDE.md §15). Full --strict runs daily in
  // check-corpus-drift.yml.
  const gate = process.argv.includes('--gate');

  if (json) {
    process.stdout.write(JSON.stringify(issues, null, 2) + '\n');
  } else {
    const fails = issues.filter(i => i.severity === 'fail');
    const warns = issues.filter(i => i.severity === 'warn');
    console.log(`[audit-critic-consensus-contamination] ${fails.length} fail, ${warns.length} warn\n`);
    for (const i of issues) {
      console.log(`  [${i.severity}] ${i.id}`);
      for (const f of i.flags) console.log(`     ${f}`);
      if (i.text) console.log(`     text: ${i.text}`);
    }
  }

  const fails = issues.filter(i => i.severity === 'fail').length;
  const warns = issues.filter(i => i.severity === 'warn').length;

  if (gate) {
    // Fail LOUD if a source-of-truth is absent: loadShowIds()/loadReviewsByShow()
    // swallow a missing data/shows.json or data/reviews.json to null, which
    // suppresses SHOW_NOT_IN_DB and the drift signals and would pass green.
    if (loadShowIds() === null || loadReviewsByShow() === null) {
      console.error('\n❌ GATE: data/shows.json or data/reviews.json missing/unparseable — cannot run the critic-consensus contamination gate.');
      process.exit(1);
    }
    const {
      shouldBlockCriticConsensusContaminationGate,
      GATE_SIGNALS,
    } = require('./lib/critic-consensus-contamination-gate');
    const gateHits = issues.filter(i => i.flags.some(f => GATE_SIGNALS.has(f.split(':')[0]))).length;
    if (shouldBlockCriticConsensusContaminationGate({ gateHits })) {
      console.error(`\n❌ GATE: ${gateHits} consensus key(s) resolve to no shows.json id (structural orphan).`);
      process.exitCode = 1;
    } else {
      console.log(`\n✓ GATE: no orphan consensus keys; staleness drift surfaced in digest (self-heals on regen).`);
    }
    return;
  }

  if (fails > 0 || (strict && warns > 0)) process.exitCode = 1;
}

if (require.main === module) main();

module.exports = { audit, FAIL_SIGNALS, REVIEWCOUNT_DRIFT_THRESHOLD, MEANSCORE_DRIFT_THRESHOLD };
