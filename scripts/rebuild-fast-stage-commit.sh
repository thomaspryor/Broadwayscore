#!/usr/bin/env bash
# rebuild-fast-stage-commit.sh — stage rebuild-fast.yml's publishable outputs and
# commit them. Extracted from the workflow's "Commit and push changes" step
# (BRO-2783) so the first commit and the post-lost-race redo
# (scripts/rebuild-fast-redo.sh) stage exactly the same paths.
#
# Env: REVIEWS_BEFORE, REVIEWS_AFTER (review counts), REBUILD_REASON.
# Exit: 0 committed, 3 nothing staged (no commit made), other = git failure.
set -euo pipefail

# Operates on the git checkout it is run from (the workflow runs it from the
# repo root); helper scripts resolve relative to this file.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$(git rev-parse --show-toplevel)"

git add data/audit/*.json 2>/dev/null || true
# Stage deletions of orphan-unscored marker files. verify-all-scored.js
# deletes them when scores have filled in; without -u those deletions
# never make it back to main and the broadcast gate stays permanently
# blocked even after the LLM ensemble resolves the orphan(s).
git add -u data/audit/ 2>/dev/null || true
bash "$SCRIPT_DIR/lib/git-add-existing.sh" public/opening-night-status.json public/status.html
git add public/data/shows/ 2>/dev/null || true
# Mobile index — kept committed in lockstep with the detail JSONs above.
git add public/data/mobile-shows.json 2>/dev/null || true
# Show Stats artifacts — regenerated by the same wrapper as the detail files.
git add public/data/stats-canon.json public/data/stats-reviews.json 2>/dev/null || true
# Lock audit-trail snapshot (Lost Boys 2026-04-27 Gap #6): /admin/locks SSR
# ships an empty page unless locks.json lands in the public tree.
git add public/data/admin/locks.json 2>/dev/null || true
# Critic-coverage admin digest (S4 — drives /admin/critic-coverage page).
git add public/data/admin/critic-coverage.json 2>/dev/null || true
git checkout -- data/reviews.json data/audience-buzz.json 2>/dev/null || true

if git diff --cached --quiet; then
  echo "rebuild-fast-stage-commit: nothing staged"
  exit 3
fi

BEFORE="${REVIEWS_BEFORE:-0}"
AFTER="${REVIEWS_AFTER:-0}"
[[ "$BEFORE" =~ ^[0-9]+$ ]] || BEFORE=0
[[ "$AFTER" =~ ^[0-9]+$ ]] || AFTER=0
DIFF=$((AFTER - BEFORE))

REASON="${REBUILD_REASON:-Scheduled safety-net refresh}"
MSG="data: Fast rebuild - $REASON"
if [ "$DIFF" -gt 0 ]; then
  MSG="$MSG (+$DIFF reviews)"
elif [ "$DIFF" -lt 0 ]; then
  MSG="$MSG ($DIFF reviews)"
fi

git commit -q -m "$MSG

Reviews: $BEFORE → $AFTER

Co-Authored-By: github-actions[bot] <github-actions[bot]@users.noreply.github.com>"
echo "rebuild-fast-stage-commit: committed $(git rev-parse --short HEAD): $MSG"
