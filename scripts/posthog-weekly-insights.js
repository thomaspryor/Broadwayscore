#!/usr/bin/env node
/**
 * posthog-weekly-insights.js — Query PostHog and create a GitHub issue summary.
 *
 * Env: POSTHOG_PERSONAL_API_KEY, GITHUB_TOKEN (auto-provided in CI)
 * Usage: node scripts/posthog-weekly-insights.js
 */

const {
  authCheck, tracked,
  getTopPages, getTopEvents, getTrafficSummary,
  getRageClicks, getTicketClicks, getSearchStats, getPromoClicks,
} = require('./lib/posthog-query');

const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
const REPO = 'thomaspryor/Broadwayscore';

function mdTable(headers, rows) {
  if (!rows || rows.length === 0) return '_No data_\n';
  const lines = [];
  lines.push(`| ${headers.join(' | ')} |`);
  lines.push(`| ${headers.map(() => '---').join(' | ')} |`);
  for (const row of rows) {
    lines.push(`| ${row.map(v => String(v ?? '—')).join(' | ')} |`);
  }
  return lines.join('\n') + '\n';
}

async function main() {
  if (!process.env.POSTHOG_PERSONAL_API_KEY) {
    console.error('POSTHOG_PERSONAL_API_KEY not set');
    process.exit(1);
  }

  await authCheck();
  console.log('PostHog auth OK');
  console.log('Querying PostHog...');

  const errors = [];
  function trackedLocal(name, fn) {
    return fn().catch(e => { errors.push(`${name}: ${e.message}`); return []; });
  }

  const [traffic, topPages, topEvents, rageClicks, ticketClicks, searchStats, promoClicks] =
    await Promise.all([
      trackedLocal('Traffic', getTrafficSummary),
      trackedLocal('Top pages', getTopPages),
      trackedLocal('Events', getTopEvents),
      trackedLocal('Rage clicks', getRageClicks),
      trackedLocal('Ticket clicks', getTicketClicks),
      trackedLocal('Search stats', getSearchStats),
      trackedLocal('Promo clicks', getPromoClicks),
    ]);

  if (errors.length > 0) {
    console.error(`${errors.length} queries failed:\n  ${errors.join('\n  ')}`);
  }
  if (errors.length === 7) {
    console.error('ALL queries failed — aborting.');
    process.exit(1);
  }

  const now = new Date();
  const weekAgo = new Date(now - 7 * 86400000);
  const dateRange = `${weekAgo.toISOString().slice(0, 10)} to ${now.toISOString().slice(0, 10)}`;

  let body = `## Weekly Analytics Summary\n**Period:** ${dateRange}\n\n`;

  if (traffic.length > 0) {
    const [users, pageviews, sessions] = traffic[0];
    body += `### Traffic Overview\n`;
    body += `- **Unique Users:** ${Number(users).toLocaleString()}\n`;
    body += `- **Pageviews:** ${Number(pageviews).toLocaleString()}\n`;
    body += `- **Sessions:** ${Number(sessions).toLocaleString()}\n\n`;
  }

  body += `### Top Pages\n${mdTable(['Page', 'Views', 'Users'], topPages)}\n`;
  body += `### Custom Events\n${mdTable(['Event', 'Count', 'Users'], topEvents)}\n`;
  body += `### Ticket Clicks\n${mdTable(['Show', 'Platform', 'Clicks'], ticketClicks)}\n`;
  body += `### Promo Clicks\n${mdTable(['Placement', 'Variant', 'Clicks'], promoClicks)}\n`;

  if (searchStats.length > 0) {
    const [total, zeroResults, uniqueSearchers] = searchStats[0];
    const zeroRate = total > 0 ? Math.round(Number(zeroResults) / Number(total) * 100) : 0;
    body += `### Search Stats\n`;
    body += `- **Total searches:** ${Number(total).toLocaleString()}\n`;
    body += `- **Zero-results rate:** ${zeroRate}%\n`;
    body += `- **Unique searchers:** ${Number(uniqueSearchers).toLocaleString()}\n\n`;
  }

  body += `### Rage Clicks (UX friction)\n${mdTable(['Page', 'Rage Clicks'], rageClicks)}\n`;
  body += `---\n🤖 Auto-generated by PostHog Weekly Insights\n`;

  console.log('\n' + body);

  if (GITHUB_TOKEN) {
    const title = `PostHog Weekly Insights — ${now.toISOString().slice(0, 10)}`;
    const res = await fetch(`https://api.github.com/repos/${REPO}/issues`, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${GITHUB_TOKEN}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ title, body, labels: ['analytics', 'automated'] }),
    });
    if (res.ok) {
      const issue = await res.json();
      console.log(`Created issue: ${issue.html_url}`);
    } else {
      console.error(`GitHub issue creation failed: ${res.status} ${await res.text()}`);
      process.exit(1);
    }
  }
}

main().catch(e => { console.error(e); process.exit(1); });
