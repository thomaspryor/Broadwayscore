#!/usr/bin/env node
'use strict';
/**
 * Audit of every same-title group in data/shows.json (BRO-7429).
 *
 *   node scripts/audit-same-title-works.js [--write] [--check]
 *
 * For each pair of productions sharing a normalized title, classifies them as the
 * same work, a different work, or unknown (scripts/lib/work-identity.js), applies
 * the hand-checked verdicts in data/audit/same-title-manual-verdicts.json (each
 * cites its evidence), and flags unknown pairs that carry a risk signal.
 * --write refreshes data/audit/same-title-works.json and docs/audits/same-title-works.md.
 * --check exits 1 when a pair the matcher still links is recorded as a different work.
 */
require('./lib/cli-help').exitOnHelp(module);
const fs = require('fs');
const path = require('path');
const { workIdentity, normalizeTitle, writerSurnames, typeConflict } = require('./lib/work-identity');

const ROOT = path.join(__dirname, '..');
const MANUAL = path.join(ROOT, 'data/audit/same-title-manual-verdicts.json');

function loadShows() {
  const r = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/shows.json'), 'utf8'));
  return Array.isArray(r) ? r : r.shows;
}

function loadManual() {
  if (!fs.existsSync(MANUAL)) return [];
  return JSON.parse(fs.readFileSync(MANUAL, 'utf8')).verdicts || [];
}

/** manual verdict lookup: pair key "a|b" (sorted) -> verdict row; a row may name a whole group. */
function manualIndex(verdicts) {
  const m = new Map();
  for (const v of verdicts) {
    for (const [x, y] of v.pairs || []) m.set([x, y].sort().join('|'), v);
  }
  return m;
}

function audit(shows, verdicts = loadManual()) {
  const manual = manualIndex(verdicts);
  const groups = new Map();
  for (const s of shows) {
    const k = normalizeTitle(s.title);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(s);
  }
  const out = [];
  for (const [key, members] of groups) {
    if (members.length < 2) continue;
    const pairs = [];
    for (let i = 0; i < members.length; i++) {
      for (let j = i + 1; j < members.length; j++) {
        const A = members[i]; const B = members[j];
        const auto = workIdentity(A, B);
        const man = manual.get([A.id, B.id].sort().join('|'));
        let verdict = auto.verdict; let basis = auto.basis; let evidence = null;
        if (man && !(A.workKey || B.workKey)) { verdict = man.verdict; basis = 'manual'; evidence = man.evidence; }
        // "unknown" pairs carry a risk flag when something suggests they may be different works.
        let risk = null;
        if (verdict === 'unknown') {
          if (typeConflict(A, B)) risk = 'type-conflict';
          else if (auto.basis === 'disjoint-writers-same-type') risk = 'disjoint-writers';
        }
        pairs.push({ a: A.id, b: B.id, verdict, basis, ...(risk ? { risk } : {}), ...(evidence ? { evidence } : {}) });
      }
    }
    const counts = { same: 0, different: 0, unknown: 0 };
    for (const p of pairs) counts[p.verdict]++;
    const atRisk = pairs.filter((p) => p.risk).length;
    out.push({
      title: members[0].title,
      members: members.map((s) => ({ id: s.id, type: s.type, category: s.category, year: (s.openingDate || '').slice(0, 4), writers: [...writerSurnames(s)], ...(s.workKey ? { workKey: s.workKey } : {}) })),
      counts,
      groupVerdict: counts.different ? 'split' : atRisk ? 'unresolved-risk' : counts.unknown ? 'unresolved-no-evidence' : 'single-work',
      pairs,
    });
  }
  out.sort((a, b) => a.title.localeCompare(b.title));
  return out;
}

function summarize(groups) {
  const g = {}; const p = { same: 0, different: 0, unknown: 0 };
  for (const x of groups) { g[x.groupVerdict] = (g[x.groupVerdict] || 0) + 1; for (const k of Object.keys(p)) p[k] += x.counts[k]; }
  return { groups: groups.length, groupVerdicts: g, pairs: p };
}

function markdown(groups, summary) {
  const L = [];
  L.push('# Same-title work audit (BRO-7429)', '');
  L.push('Generated by `node scripts/audit-same-title-works.js --write`. Every group of productions sharing a normalized title in `data/shows.json`, and whether the pairs are one work.', '');
  L.push(`- Groups: **${summary.groups}**`, `- Pairs: same work ${summary.pairs.same}, different work ${summary.pairs.different}, unknown ${summary.pairs.unknown}`);
  L.push(`- Group verdicts: ${Object.entries(summary.groupVerdicts).map(([k, v]) => `${k} ${v}`).join(', ')}`, '');
  L.push('Verdict basis: `linked` (transferOf), `shared-writer` (accent-folded surname), `workKey` (explicit), `writers+type` (no shared writer and musical vs play), `manual` (hand-checked, evidence cited below), `one-side-no-writers` / `no-writers` (nothing to compare; the matcher keeps the link).', '');
  L.push('## Different works (matcher separates them)', '');
  for (const gr of groups.filter((x) => x.counts.different)) {
    L.push(`### ${gr.title}`);
    for (const p of gr.pairs.filter((q) => q.verdict === 'different')) L.push(`- \`${p.a}\` vs \`${p.b}\`: ${p.basis}${p.evidence ? ` (${p.evidence})` : ''}`);
    L.push('');
  }
  L.push('## Unresolved with a risk signal (no writers to settle them)', '');
  for (const gr of groups.filter((x) => x.groupVerdict === 'unresolved-risk')) {
    L.push(`- **${gr.title}**: ${gr.pairs.filter((p) => p.risk).slice(0, 6).map((p) => `${p.a} / ${p.b} (${p.risk})`).join('; ')}`);
  }
  L.push('', '## Every group', '', '| Title | Members | Verdict | same / different / unknown |', '|---|---|---|---|');
  for (const gr of groups) L.push(`| ${gr.title.replace(/\|/g, '/')} | ${gr.members.length} | ${gr.groupVerdict} | ${gr.counts.same} / ${gr.counts.different} / ${gr.counts.unknown} |`);
  return L.join('\n') + '\n';
}

function main() {
  const shows = loadShows();
  const groups = audit(shows);
  const summary = summarize(groups);
  if (process.argv.includes('--write')) {
    fs.mkdirSync(path.join(ROOT, 'data/audit'), { recursive: true });
    fs.mkdirSync(path.join(ROOT, 'docs/audits'), { recursive: true });
    fs.writeFileSync(path.join(ROOT, 'data/audit/same-title-works.json'), JSON.stringify({ summary, groups }, null, 1) + '\n');
    fs.writeFileSync(path.join(ROOT, 'docs/audits/same-title-works.md'), markdown(groups, summary));
  }
  console.log(JSON.stringify(summary));
  if (process.argv.includes('--check')) {
    const { differentWorks } = require('./lib/work-identity');
    const byId = Object.fromEntries(shows.map((s) => [s.id, s]));
    const leaks = [];
    for (const gr of groups) for (const p of gr.pairs) if (p.verdict === 'different' && !differentWorks(byId[p.a], byId[p.b])) leaks.push(`${p.a} / ${p.b}`);
    if (leaks.length) { console.error(`${leaks.length} manual different-work pairs the matcher still links:\n${leaks.join('\n')}`); process.exit(1); }
  }
}
if (require.main === module) main();
module.exports = { audit, summarize, loadManual };
