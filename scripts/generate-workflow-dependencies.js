#!/usr/bin/env node
/**
 * Generates .github/workflows/DEPENDENCIES.md from the workflow files (BRO-934).
 *   node scripts/generate-workflow-dependencies.js          # rewrite the doc
 *   node scripts/generate-workflow-dependencies.js --check  # exit 1 if the doc is stale
 * Parsing lives in scripts/lib/workflow-dependency-graph.js.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const g = require('./lib/workflow-dependency-graph.js');
const { hasHelpFlag } = require('./lib/cli-help.js');

const WF_DIR = path.join(__dirname, '..', '.github', 'workflows');
const OUT = path.join(WF_DIR, 'DEPENDENCIES.md');
const CLASSES = ['rebuild', 'scoring', 'scraping', 'deploy', 'other'];

// Hash of the graph facts a human must re-document when they change (edges, cross-repo writers,
// their concurrency). Secrets lists and unrelated workflow churn do not move it, so an
// unrelated land is never blocked by a stale doc.
function fingerprint(workflows) {
  const { edges } = g.buildGraph(workflows);
  const facts = {
    edges: edges.map((e) => `${e.via}:${e.from}>${e.to}`).sort(),
    writers: workflows.filter((w) => w.pushesCrossRepo).map((w) => `${w.file}|${w.concurrency.map((c) => `${c.group}/${c.cancelRaw}`).join(',')}`).sort(),
  };
  return require('crypto').createHash('sha256').update(JSON.stringify(facts)).digest('hex').slice(0, 16);
}

const node = (f) => f.replace(/\.ya?ml$/, '').replace(/[^\w]/g, '_');
const cancelOf = (c) => (c.cancelRaw === null ? 'default(false)' : c.cancelRaw);

function render(workflows) {
  const { edges, unresolved } = g.buildGraph(workflows);
  const L = [];
  L.push('# Workflow dependency graph');
  L.push('');
  L.push('<!-- GENERATED by scripts/generate-workflow-dependencies.js. Do not edit; run it and commit. CI: scripts/validate-workflow-dependencies.test.mjs -->');
  L.push(`<!-- graph-fingerprint: ${fingerprint(workflows)} -->`);
  L.push('');
  L.push('Three repos share one automation fabric. Pushes in one fire workflows in another, so every');
  L.push('writer needs a known place in this graph.');
  L.push('');
  L.push('| Repo | Role | Workflows | Reached from this repo via |');
  L.push('|---|---|---|---|');
  L.push(`| \`thomaspryor/Broadwayscore\` (main) | code + all pipelines (${workflows.length} workflows here) | this directory | n/a |`);
  L.push('| `thomaspryor/broadway-scorecard-data` (private) | core data: shows.json, reviews.json, commercial.json | `submit-indexnow.yml`, `theatr-review-discovery.yml` (own repo) | `checkout-core-data` (read), `push-core-data` (write) |');
  L.push('| `thomaspryor/broadway-review-texts` (private) | review texts + aggregator archive | none checked in locally | `checkout-review-texts`/`checkout-aggregator-archive` (read), `push-review-texts`/`push-aggregator-archive` (write) |');
  L.push('');
  L.push('The two private repos are written only by workflows in this repo (via the composite actions above), plus');
  L.push('the two data-repo workflows listed. A push into a private repo does not itself trigger main workflows;');
  L.push('main-side `workflow_run` / explicit dispatches below are what chain the pipeline.');
  L.push('');

  L.push('## workflow_run chain');
  L.push('');
  L.push('```mermaid');
  L.push('graph LR');
  const wr = edges.filter((e) => e.via === 'workflow_run');
  for (const e of wr) L.push(`  ${node(e.from)}["${e.from}"] --> ${node(e.to)}["${e.to}"]`);
  L.push('```');
  L.push('');
  L.push('| Triggered workflow | Fires after |');
  L.push('|---|---|');
  const byTo = new Map();
  for (const e of wr) byTo.set(e.to, [...(byTo.get(e.to) || []), e.from]);
  for (const [to, froms] of [...byTo].sort()) L.push(`| \`${to}\` | ${froms.map((f) => `\`${f}\``).join(', ')} |`);
  if (unresolved.length) {
    L.push('');
    L.push('Unresolved workflow_run names (BROKEN: the trigger can never fire):');
    for (const u of unresolved) L.push(`- \`${u.file}\` waits on "${u.name}"`);
  }
  L.push('');

  L.push('## Explicit dispatches (workflow -> workflow)');
  L.push('');
  L.push('| From | Dispatches |');
  L.push('|---|---|');
  const disp = new Map();
  for (const e of edges.filter((x) => x.via === 'dispatch')) disp.set(e.from, [...(disp.get(e.from) || []), e.to]);
  for (const [from, tos] of [...disp].sort()) L.push(`| \`${from}\` | ${tos.map((t) => `\`${t}\``).join(', ')} |`);
  L.push('');

  const ext = workflows.flatMap((w) => w.externalDispatches.map((e) => `| \`${w.file}\` | \`thomaspryor/${e.repo}\` | \`${e.file}\` |`));
  if (ext.length) {
    L.push('Dispatches into other repos (iOS app, outside the three-repo data fabric):');
    L.push('');
    L.push('| From | Repo | Workflow |');
    L.push('|---|---|---|');
    L.push(...[...new Set(ext)].sort());
    L.push('');
  }

  L.push('## Cross-repo writers');
  L.push('');
  L.push('Every workflow that pushes to a private repo. Each must carry a concurrency group (validator-enforced; exceptions listed in the test).');
  L.push('');
  L.push('| Workflow | Class | Writes | Concurrency (group, cancel-in-progress) |');
  L.push('|---|---|---|---|');
  for (const w of workflows.filter((x) => x.pushesCrossRepo)) {
    const repos = [...new Set(w.repoEdges.filter((e) => e.mode === 'push').map((e) => e.repo))].join(', ');
    const c = w.concurrency.map((x) => `\`${x.group}\` (${cancelOf(x)}${x.level === 'job' ? ', job-level' : ''})`).join('; ') || '**none**';
    L.push(`| \`${w.file}\` | ${w.class} | ${repos} | ${c} |`);
  }
  L.push('');

  L.push('## Concurrency classes and groups');
  L.push('');
  L.push('Classes: **rebuild**, **scoring**, **scraping**, **deploy** (label derived from the workflow filename, see');
  L.push('`CLASS_RULES` in scripts/lib/workflow-dependency-graph.js). Serialization is enforced by concurrency *groups*.');
  L.push('A single shared group per class is deliberately NOT used: GitHub keeps one running and ONE pending run per group,');
  L.push('so a 40-member `scraping` group would cancel queued runs (the Beaches / Rocky Horror opening-night incident,');
  L.push('see rebuild-fast.yml). Workflows that must exclude each other share a *resource* group (`shows-json-writer`,');
  L.push('`rebuild-reviews`, `data-grosses-writers`, ...); everything else uses its own per-workflow group, so different');
  L.push('classes and unrelated jobs run in parallel.');
  L.push('');
  const groups = new Map();
  for (const w of workflows) {
    for (const c of w.concurrency) {
      const key = c.group.replace(/\$\{\{.*?\}\}/g, '*').replace(/-$/, '');
      const e = groups.get(key) || { members: [], cancel: new Set() };
      e.members.push(w.file);
      e.cancel.add(cancelOf(c));
      groups.set(key, e);
    }
  }
  const shared = [...groups].filter(([, v]) => v.members.length > 1).sort();
  L.push('Groups shared by 2+ workflows:');
  L.push('');
  L.push('| Group | cancel-in-progress | Members |');
  L.push('|---|---|---|');
  for (const [k, v] of shared) L.push(`| \`${k}\` | ${[...v.cancel].join('/')} | ${v.members.map((m) => `\`${m}\``).join(', ')} |`);
  L.push('');
  L.push('Workflows without any concurrency block, by class (read-only / alerting / test jobs mostly):');
  L.push('');
  for (const cls of CLASSES) {
    const none = workflows.filter((w) => w.class === cls && w.concurrency.length === 0).map((w) => w.file);
    if (none.length) L.push(`- **${cls}** (${none.length}): ${none.map((f) => `\`${f}\``).join(', ')}`);
  }
  L.push('');

  L.push('## Secrets used by cross-repo writers');
  L.push('');
  L.push('| Secret | Used by (cross-repo writers) |');
  L.push('|---|---|');
  const sec = new Map();
  for (const w of workflows.filter((x) => x.pushesCrossRepo)) for (const s of w.secrets) sec.set(s, [...(sec.get(s) || []), w.file]);
  for (const [s, fs_] of [...sec].sort()) L.push(`| \`${s}\` | ${fs_.length} workflows${fs_.length <= 3 ? ': ' + fs_.map((f) => `\`${f}\``).join(', ') : ''} |`);
  L.push('');
  L.push('Cross-repo auth is `CORE_DATA_TOKEN` / `REVIEW_TEXTS_TOKEN` / `REPO_TOKEN` passed to the composite actions. Full per-workflow secret audit: `node scripts/audit-workflow-secret-gaps.js`.');
  L.push('');

  L.push('## Freeze (manual-intervention nights)');
  L.push('');
  L.push('Run the **Automation Freeze** workflow (`automation-freeze.yml`, action=freeze, hours=8): disables non-critical cron and');
  L.push('`workflow_run` workflows, never `CRITICAL_CRONS` or the opening-night pipeline, and re-enables exactly what it disabled');
  L.push('(manually or automatically at expiry). Runbook: `memory/opening-night-freeze-runbook.md`.');
  L.push('');
  return L.join('\n');
}

function main() {
  if (hasHelpFlag(process.argv.slice(2))) {
    console.log('usage: generate-workflow-dependencies.js [--check]   (writes .github/workflows/DEPENDENCIES.md)');
    return;
  }
  const out = render(g.loadWorkflows(WF_DIR));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) {
      console.error('DEPENDENCIES.md is stale: run `node scripts/generate-workflow-dependencies.js` and commit.');
      process.exit(1);
    }
    console.log('DEPENDENCIES.md up to date');
    return;
  }
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${out.split('\n').length} lines)`);
}

module.exports = { render, fingerprint };
if (require.main === module) main();
